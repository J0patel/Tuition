export const generateInitialAttendance = (): AttendanceRecord[] => {
  const records: AttendanceRecord[] = [];
  const statuses: ('Present' | 'Absent' | 'Leave' | 'Holiday')[] = ['Present', 'Present', 'Present', 'Present', 'Present', 'Absent', 'Leave'];
  
  // Last 3 months: June, July, August 2026
  const dates: string[] = [];
  for (let month = 6; month <= 8; month++) {
    const daysInMonth = month === 6 ? 30 : 31;
    const maxDay = (month === 8) ? 4 : daysInMonth; // up to current date Aug 4
    for (let day = 1; day <= maxDay; day++) {
      const dayStr = day < 10 ? `0${day}` : `${day}`;
      const monthStr = month < 10 ? `0${month}` : `${month}`;
      const dateStr = `2026-${monthStr}-${dayStr}`;
      
      const dateObj = new Date(dateStr);
      if (dateObj.getDay() === 0) continue; // Skip Sundays

      dates.push(dateStr);
    }
  }

  let idCounter = 1;
  initialStudents.forEach(student => {
    dates.forEach((dateStr, idx) => {
      let status: 'Present' | 'Absent' | 'Leave' | 'Holiday' = 'Present';
      if (idx % 14 === 0) status = 'Holiday';
      else if ((student.id + idx) % 9 === 0) status = 'Absent';
      else if ((student.id + idx) % 15 === 0) status = 'Leave';

      records.push({
        id: idCounter++,
        studentId: student.id,
        studentName: student.studentName,
        batchId: student.batchId,
        attendanceDate: dateStr,
        status,
        remarks: status === 'Absent' ? 'Uninformed Absence' : status === 'Leave' ? 'Family Event' : undefined,
        markedBy: 1
      });
    });
  });

  return records;
};

